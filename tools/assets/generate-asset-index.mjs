import {
  CATALOG,
  json,
  read,
  write,
  duplicateGroups,
  isMain,
} from "./asset-utils.mjs";
const generated = "docs/assets/generated/";
const escapeHtml = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll('"', "&quot;");
export function generateIndex() {
  const { assets } = json(CATALOG + "asset-manifest.v1.json"),
    { packs } = json(CATALOG + "destination-packs.v1.json"),
    { entries } = json(CATALOG + "legacy-inventory.v1.json");
  const local = assets.filter((a) => a.runtime.kind === "local");
  const runtimeBytes = local.reduce((sum, a) => sum + a.integrity.bytes, 0);
  const groups = duplicateGroups([
    ...entries,
    ...local.map((a) => ({
      path: "public" + a.runtime.path,
      sha256: a.integrity.sha256,
    })),
  ]);
  const table = (items) =>
    [
      "| ID | Status | Authenticity | File / reference |",
      "| --- | --- | --- | --- |",
      ...items.map(
        (a) =>
          `| ${a.id} | ${a.status} | ${a.authenticity} | ${a.runtime.kind === "local" ? `[SVG](../../..${a.runtime.path.replace("/media/", "/public/media/")})` : a.runtime.kind} |`,
      ),
      "",
    ].join("\n");
  let index =
    "# Asset Library Index v1\n\nGenerated by `npm run assets:index`. Do not edit generated reports manually.\n\n";
  index += `## Counts / Size Summary\n\n${assets.length} registered assets: ${local.length} original local SVG, ${assets.filter((a) => a.status === "acquisition_required").length} acquisition-only slots; ${packs.length} packs. New runtime bytes: ${runtimeBytes}. No new raster.\n\n`;
  index += `## Legacy / Protected\n\n${entries.length} legacy files; ${entries.filter((e) => e.protected).length} protected. All remain legacy_review_required, even when provenance was found. Literal-reference discovery is not a complete usage graph.\n\n[Machine-readable inventory](../catalog/legacy-inventory.v1.json) · [Aliases, report only](../catalog/asset-aliases.v1.json)\n\n`;
  for (const [title, type] of [
    ["POI Categories", "poi-categories"],
    ["Transport", "transport"],
    ["Map Markers", "map-markers"],
    ["Placeholders", "placeholders"],
    ["States", "states"],
    ["Destination Packs", "destination_placeholder"],
  ])
    index +=
      `## ${title}\n\n` + table(assets.filter((a) => a.assetType === type));
  for (const [title, statuses] of [
    ["Approved", ["approved"]],
    ["Provider Only", ["provider_only"]],
    ["Acquisition Required", ["acquisition_required"]],
    ["Rejected / Expired", ["rejected", "expired"]],
  ])
    index +=
      `## ${title}\n\n` +
      table(assets.filter((a) => statuses.includes(a.status)));
  write(generated + "asset-library-index.md", index);
  write(
    generated + "duplicate-report.md",
    `# Duplicate Report\n\n${groups.length} exact SHA-256 groups. No files deleted, merged or moved. Canonical aliases are audit suggestions only, not runtime redirects.\n\n` +
      groups
        .map(
          (g) =>
            `## ${g.sha256}\n\n${g.paths.map((p) => `- \`${p}\``).join("\n")}\n`,
        )
        .join("\n"),
  );
  const all = [
    ...entries.map((e) => ({ path: e.path, bytes: e.bytes, legacy: true })),
    ...local.map((a) => ({
      path: "public" + a.runtime.path,
      bytes: a.integrity.bytes,
      legacy: false,
    })),
  ].sort((a, b) => b.bytes - a.bytes || a.path.localeCompare(b.path));
  write(
    generated + "size-report.md",
    `# Size Report\n\nNew SVG runtime: **${runtimeBytes} bytes** / 2,000,000 target. Legacy: ${entries.reduce((n, e) => n + e.bytes, 0)} bytes. New raster: 0. Existing oversized files are reported, not recompressed.\n\n| File | Bytes | Scope | Over 1 MB |\n| --- | ---: | --- | --- |\n` +
      all
        .map(
          (e) =>
            `| ${e.path} | ${e.bytes} | ${e.legacy ? "legacy (unchanged)" : "TASK-013"} | ${e.bytes > 1000000 ? "yes — legacy exception" : "no"} |`,
        )
        .join("\n") +
      "\n",
  );
  const cards = (items) =>
    items
      .map(
        (a) =>
          `<article><div class="samples"><div class="light">${read("public" + a.runtime.path)}</div><div class="dark">${read("public" + a.runtime.path)}</div></div><h3>${escapeHtml(a.entity.id)}</h3><small>${a.integrity.bytes} B · symbolic</small></article>`,
      )
      .join("\n");
  const sections = [
    "poi-categories",
    "transport",
    "map-markers",
    "placeholders",
    "states",
    "destination_placeholder",
  ]
    .map(
      (group) =>
        `<section id="${group}" class="${["placeholders", "states", "destination_placeholder"].includes(group) ? "wide" : ""}"><h2>${group.replaceAll("_", " ")} <span>${local.filter((a) => a.assetType === group).length}</span></h2><div class="grid">${cards(local.filter((a) => a.assetType === group))}</div></section>`,
    )
    .join("\n");
  write(
    "assets/design/asset-library/previews/asset-library-preview.html",
    `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>TravelAssist — Asset Library Review</title><style>
*{box-sizing:border-box}body{margin:0;padding:40px;background:#fbf4ea;color:#334657;font:15px/1.5 system-ui,sans-serif}header{max-width:900px;margin-bottom:40px}h1{font:500 38px/1.2 Georgia,serif;margin:12px 0}header p{max-width:740px}nav{display:flex;gap:18px;flex-wrap:wrap}a{color:#9d514c}h2{font-size:20px;margin:32px 0 16px}h2 span{color:#a06157;font-size:14px}section{scroll-margin-top:16px}article{min-width:0;background:#fffaf4;border:1px solid #eadfd3;border-radius:14px;overflow:hidden;padding:12px}h3{font-size:12px;overflow-wrap:anywhere;margin:10px 0 2px}small{font-size:11px;color:#68747a}.grid{display:grid;grid-template-columns:repeat(8,minmax(0,1fr));gap:12px}.samples{display:flex;gap:5px}.samples>div{width:50%;height:58px;display:flex;align-items:center;justify-content:center;border-radius:8px}.light{background:#fff;color:#475665}.dark{background:#344353;color:#fffaf4}svg{width:24px;height:24px}#map-markers svg{width:32px;height:40px}.wide .grid{grid-template-columns:repeat(4,minmax(0,1fr))}.wide .samples>div{height:auto;aspect-ratio:1.5}.wide svg{width:100%;height:auto}footer{margin-top:36px;border-top:1px solid #ddd3c9;padding-top:18px}@media(max-width:750px){body{padding:20px}.grid{grid-template-columns:repeat(3,minmax(0,1fr))}.wide .grid{grid-template-columns:repeat(2,minmax(0,1fr))}}
</style></head><body><header><small>TRAVELASSIST / TASK-013-A / SOURCE REVIEW</small><h1>A small, coherent visual vocabulary.</h1><p>64 shared originals + 5 destination placeholders. Warm paper, coral and blue-grey; no downloaded icon pack, photographs or accurate geographic claims. Preview checks light/dark rendering at intended icon sizes. Photos remain procurement requests.</p><nav><a href="#poi-categories">POI</a><a href="#transport">Transport</a><a href="#map-markers">Markers</a><a href="#destination_placeholder">Destinations</a></nav></header>${sections}<footer>Original geometric SVG for TravelAssist · ${runtimeBytes} bytes · Semantic names supplied by consuming components. Static loading glyph; no motion required. Not a production application route.</footer></body></html>\n`,
  );
  return { local: local.length, runtimeBytes, duplicateGroups: groups.length };
}
if (isMain(import.meta.url)) console.log(generateIndex());
