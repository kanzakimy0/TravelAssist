export function validPath(ids, from, to, byEdge, context) {
  return baseValidPath(ids, from, to, byEdge, context);
}
export function queryWitness(edges, from, to, context) {
  const ids = queryGraph(edges, from, to, context);
  if (ids === null) return null;
  const by = new Map(edges.map((e) => [e.edgeId, e]));
  invariant(
    validPath(ids, from, to, by, context),
    "CONDITIONAL_WITNESS_INVALID",
  );
  const conditions = [
    ...new Map(
      ids
        .map((id) => by.get(id))
        .filter((e) => e.accessContract)
        .map((e) => [
          e.accessContractSha256,
          { sha256: e.accessContractSha256, contract: e.accessContract },
        ]),
    ).values(),
  ];
  return {
    kind: conditions.length
      ? "CONDITIONAL_PLANNING_PATH"
      : "UNCONDITIONAL_TOPOLOGY_PATH",
    edgeIds: ids,
    conditions,
    travelDate: conditions.length ? context.travelDate : null,
    bookingConfirmed: false,
    bookingCapacityGuaranteed: false,
    reservationIntentOnly: conditions.length > 0,
    unconditional: conditions.length === 0,
  };
}
// Separate structural witness; does not mutate a deficit, ordinary connectivity,
// applicability review or global gate. Exact national and interface paths must
// still be admitted/generated by existing production proofs before integration.
export function publicStructuralRoundTrip(edges, from, to, context) {
  if (context?.publicStructureOnly !== true) return null;
  const a = queryWitness(edges, from, to, context),
    b = queryWitness(edges, to, from, context);
  if (!a || !b || !a.conditions.length || !b.conditions.length) return null;
  if (
    [...a.conditions, ...b.conditions].some(
      (c) => c.contract.audience !== "PUBLIC",
    )
  )
    return null;
  return {
    kind: "EVIDENCED_PUBLIC_CONDITIONAL_ROUND_TRIP",
    from,
    to,
    outbound: a,
    inbound: b,
    ordinaryDefaultReachableBoth:
      queryGraph(edges, from, to) !== null &&
      queryGraph(edges, to, from) !== null,
    globalGateClosed: false,
  };
}
